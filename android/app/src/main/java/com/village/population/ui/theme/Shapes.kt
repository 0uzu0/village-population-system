package com.village.population.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 形状令牌（shape tokens）。
 *
 * 为什么要有这一层：改版前圆角值是「一个组件一个样」——
 * StatCard 10dp、SectionCard 12dp、入口 11dp、输入框 10dp、标签 10dp，
 * 没有任何两个对得上。单看都不难看，摆到一屏里就是「不整齐」：
 * 同一屏六张卡片三种圆角，视觉上会读成三个层级，而它们其实是平级的。
 *
 * 所以把「一张卡片应该长什么样」收敛成这里的一处定义：
 * 改版只改这一个文件，所有卡片同时变，不存在漏改的卡片。
 *
 * 注意与 [AppTokens] 的分工：那边管**色值**（逐项对应设计说明 HTML），
 * 这边管**形状与阴影**——色值被 `AppTokensTest` 钉死，形状没有被测试钉，
 * 所以改形状不需要动测试，但也意味着改之前要先过设计稿评审。
 */
object AppShapes {

    /**
     * 卡片圆角。
     *
     * 20dp 的依据：正文正文行高 22sp 的比例下，20dp 约等于两行文字高的一半，
     * 圆角与内容块形成同源比例；再大（28dp+）在 360dp 宽的中低端机上
     * 会把卡片横向切得太碎，反而显小。
     */
    val card = 20.dp

    /**
     * 卡片阴影。
     *
     * 4dp 是「压得住但不糊」的一档：低于 3dp 在户外强光下看不出层次，
     * 高于 6dp 卡片边缘会发灰（安卓阴影是按遮盖关系绘制的，不是高斯模糊，
     *  elevation 给的只是「遮挡强度」的估算）。
     *
     * 与描边的关系：保留原有 1px 浅描边 (`tokens.line`) 作为兜底——
     *  阴影在部分低端机的 Layer 合成里可能被裁掉，描边保证层次不消失。
     */
    val cardElevation = 4.dp

    /**
     * 入口 / 按钮 / 输入框的中等圆角，约为卡片的一半。
     *
     * 「外大内小」是让嵌套元素（卡片里放按钮）不糊成一团的常规做法：
     * 控件圆角小于容器圆角时，包裹关系一眼可读；两者相等时边界会「粘」在一起。
     * 此前 FormField 是 10dp、QuickActionTile 是 11dp——各差 1dp，
     * 没有理由，只是没人管；统一收到这里。
     */
    val control = 14.dp

    /**
     * 胶囊 / 徽章：全圆角。宽度由内容决定，圆角必须给到 50% 才成胶囊。
     *
     * 用于：我的页版本号胶囊、待核查原因徽章、标签 chip。
     * 不用 PercentCornerSize(50)：对固定高度的控件，50% 与大数值等价且可读性更好。
     */
    val chip = 50.dp
}
