-- =============================================================
-- V022 人员档案乐观锁（并发编辑保护）
-- =============================================================
-- 背景：编辑接口是「全量覆盖」语义，两个人同时打开同一份档案、各自保存，
-- 后保存的那次会把先保存的改动静默覆盖掉——没有任何提示，事后也没人知道
-- 中间那份改动去哪了。村里的实际场景很常见：一个人在便民点改地址，
-- 另一个人在外勤用手机补电话，两边都以为存上了。
--
-- 做法：每行一个版本号。前端打开编辑时记下它，保存时原样带回；
-- 服务端 UPDATE ... WHERE id = ? AND row_version = ? 并 +1。
-- 版本对不上就说明期间有人改过，返回 409 让调用方刷新后重试。
--
-- 默认 0；老客户端不带版本号时跳过校验（向后兼容），新客户端一律带。
ALTER TABLE `person`
  ADD COLUMN `row_version` INT NOT NULL DEFAULT 0
    COMMENT '乐观锁版本号：每次编辑 +1，编辑请求需带上读取时的值';
