-- =============================================================
-- V020 登录令牌版本号（JWT 撤销）
-- =============================================================
-- 背景：登录有效期从 12h 延长到 7d 后，JWT「无状态」的副作用被放大——
-- 改密码、停用账号都不会让已签发的 token 失效，手机丢了改密码，捡到的人
-- 仍能继续用 7 天。
--
-- 做法：给每个用户一个版本号，签发 token 时写进 payload，每次请求与库里比对，
-- 对不上即 401。改密码 / 停用账号时 +1，所有已签发的 token 立刻作废。
-- 默认 0 且旧 token 缺少 tv 时按 0 处理，所以本迁移不会让现有登录掉线。
ALTER TABLE `sys_user`
  ADD COLUMN `token_version` INT NOT NULL DEFAULT 0
    COMMENT '令牌版本：改密/停用时 +1，使已签发的旧 token 立即失效';
