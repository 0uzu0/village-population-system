-- =============================================================
-- V026 下线家庭标签功能（v2.3.1，2026-10）
-- =============================================================
-- 背景（用户决策）：
--   家庭标签（低保家庭 / 五保家庭等家庭级认定）与人口标签是两套并行体系，
--   实际使用中村里从来只在人口维度打低保/特困标签，家庭级标签从未参与
--   任何统计口径（工作台 / 重点人群 / 导出均不取数），界面却要为此多维护
--   一套「家庭标签」区块与筛选。决定**整体下线**，包括：
--     · family_tag 关联表
--     · tag_definition 里 object_type='FAMILY' 的全部标签定义（含自建）
--     · tag_change_log 里 object_type='FAMILY' 的变更流水
--
-- 口径说明（删除前的最后记录）：
--   低保统计此后只有个人级「低保对象」（LOW_INCOME_PERSON）一个口径，
--   不再有「家庭级低保家庭数 + 个人级低保对象数」的双口径。
--
-- ⚠️ 可重跑：全部用 IF EXISTS / 条件删除。
-- ⚠️ 删除顺序：先删引用（family_tag、tag_change_log）再删定义（tag_definition），
--    与库内「无外键、手动级联」的既有约定一致。
-- -----------------------------------------------

-- 1. 家庭-标签关联（先删引用）
DROP TABLE IF EXISTS `family_tag`;

-- 2. 家庭标签变更流水（标签历史页不再提供 FAMILY 维度）
DELETE FROM `tag_change_log` WHERE `object_type` = 'FAMILY';

-- 3. 家庭级标签定义（系统内置 + 用户自建一并清理）
DELETE FROM `tag_definition` WHERE `object_type` = 'FAMILY';
