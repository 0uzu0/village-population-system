-- V015 删除「网格数据范围」权限维度
--
-- 背景：这套系统最初预留了「网格员只看本网格数据」的数据范围机制，
-- 落到代码里就是 sys_role.data_scope + rbac.ts 的 buildGridFilter()。
-- 但 buildGridFilter() 从落地第一天起就是恒返回空条件的空实现，
-- 也就是说 data_scope 这个列**从来没有被任何一句 SQL 读过**：
--   · 各模块的调用点写的是「取到范围就拼进 WHERE」，取到空串等于没拼；
--   · 权限校验完全由 sys_role_permission 的权限码负责，与数据范围无关。
-- 结论：它既没起作用，又容易被后来人误读成「权限已经按网格隔离了」，
-- 是纯粹的理解成本。业务上也不需要这个维度——本系统的数据范围就是全量。
--
-- 本次一并删掉代码侧的 buildGridFilter() 与全部调用点，这里把列也去掉，
-- 让「系统里没有网格员权限这个概念」在数据库层面同样成立。
--
-- 注意：不要改成「带存在性判断」的 DROP COLUMN 变体——那是 MariaDB 的扩展语法，
-- MySQL 8.0 会直接报语法错误。迁移器按 schema_migrations 表保证本文件只执行一次，
-- 「列已经不存在」这种情况不会发生，也不需要判断。
ALTER TABLE `sys_role` DROP COLUMN `data_scope`;
